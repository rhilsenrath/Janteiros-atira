"""Per-task model metadata; concurrent workers never share mutable call settings."""
from contextlib import contextmanager
from contextvars import ContextVar

current_call = ContextVar('model_call_context', default={})


@contextmanager
def model_context(**settings):
    token = current_call.set({**current_call.get(), **settings})
    try:
        yield
    finally:
        current_call.reset(token)


def compact_facts(value):
    """Keep facts and source IDs in decisions; quotations stay in the evidence store."""
    if isinstance(value, dict):
        result = {key: compact_facts(item) for key, item in value.items() if key != 'evidence'}
        if value.get('evidence'):
            result['source_ids'] = list(dict.fromkeys(item['id'] for item in value['evidence']))
        return result
    if isinstance(value, list):
        return [compact_facts(item) for item in value]
    return value


def business_schema(schema):
    """Evidence metadata is attached by Python, never generated by the model."""
    if isinstance(schema, list):
        return [business_schema(item) for item in schema]
    if not isinstance(schema, dict):
        return schema
    result = {key: business_schema(value) for key, value in schema.items()}
    if 'properties' in result:
        result['properties'].pop('evidence', None)
        if 'required' in result:
            result['required'] = [key for key in result['required'] if key != 'evidence']
    if '$defs' in result:
        result['$defs'].pop('Evidence', None)
    return result
